// Re-skins the original pages in the new design WITHOUT changing their content.
// - <head>: kept exactly (title, meta, canonical, schema); only the old font + styles.css links
//   are swapped for the new stylesheets.
// - <main>: copied byte for byte from the original commit.
// - Header, footer and mobile action bar: shared partials with the original menu and footer content.
// - assets/css/pages.css: the old styles.css, scoped to <main> and put in the lowest cascade layer,
//   with its colour and font tokens remapped to the design system (see bridge.css).
// Usage: node redesign/_build/reskin.js [file.html ...]   (no args = every original page except index.html)
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const ORIGINAL = '2a58002'; // last commit before the redesign touched any page
const git = (args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' });
const partial = (n) => fs.readFileSync(path.join(__dirname, 'partials', n), 'utf8');
const SKIP = /bridge|^review\.html$|^index\.html$/;

// 1. Build assets/css/pages.css from the original styles.css
const oldCss = git(['show', `${ORIGINAL}:styles.css`]);
const keyframes = [];
const scoped = oldCss
  .replace(/@keyframes[^{]+\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, (m) => { keyframes.push(m); return ''; })
  .replace(/:root\s*\{/g, ':scope {');
const bridge = fs.readFileSync(path.join(__dirname, 'bridge.css'), 'utf8');
const pagesCss = `/* GENERATED by redesign/_build/reskin.js: original page styles, scoped to <main>, layered between base and layout. Do not edit. */
@layer tokens, base, legacy, layout, components, sections, utilities;
${keyframes.join('\n')}
@layer legacy {
@scope (main) {
${scoped}
${bridge}
}
}
`;
fs.writeFileSync(path.join(ROOT, 'assets', 'css', 'pages.css'), pagesCss);
console.log('pages.css', Math.round(pagesCss.length / 1024) + ' KB');

// 2. Pages
const files = process.argv.slice(2).length ? process.argv.slice(2)
  : git(['ls-tree', '--name-only', ORIGINAL]).split('\n').filter((f) => f.endsWith('.html') && !SKIP.test(f));

const header = partial('header.html');
const footer = partial('footer.html');

for (const file of files) {
  let html = git(['show', `${ORIGINAL}:${file}`]);

  // Head: swap stylesheets only
  html = html.replace(/<link[^>]+fonts\.(googleapis|gstatic)\.com[^>]*>/g, '')
    .replace(/<noscript>\s*<\/noscript>/g, '')
    .replace(/<link rel="stylesheet" href="styles\.css[^"]*">/, '')
    .replace('</head>', `  <link rel="stylesheet" href="assets/css/pages.css">
  ${partial('head-assets.html').trim()}
</head>`);

  // Header: from the skip link to </header>
  const hs = html.indexOf('<a class="skip-link"'); const he = html.indexOf('</header>') + '</header>'.length;
  if (hs < 0 || he < 9) throw new Error(`${file}: header not found`);
  let h = header;
  // Mark the current page in the menu
  h = h.replace(new RegExp(`(<a href="${file.replace('.', '\\.')}")`, 'g'), '$1 aria-current="page"');
  html = html.slice(0, hs) + h + html.slice(he);

  // Footer and mobile actions
  const fs0 = html.indexOf('<footer'); const fe = html.indexOf('</footer>') + '</footer>'.length;
  html = html.slice(0, fs0) + footer.trim() + html.slice(fe);
  html = html.replace(/<nav class="mobile-actions"[\s\S]*?<\/nav>/, '');

  // Small script for the new menu and map; original scripts stay as they were
  html = html.replace('</body>', '<script src="assets/js/site.js" defer></script>\n</body>');

  fs.writeFileSync(path.join(ROOT, file), html);
  console.log('reskinned', file);
}
